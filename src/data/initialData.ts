export function getRandomInnovativeHook(category?: string): InnovativeHookItem {
  const filtered = category && category !== 'all'
    ? INITIAL_INNOVATIVE_HOOKS.filter(h => h.category === category)
    : INITIAL_INNOVATIVE_HOOKS;
  const pool = filtered.length > 0 ? filtered : INITIAL_INNOVATIVE_HOOKS;
  const idx = Math.floor(Math.random() * pool.length);
  return pool[idx];
}

